-- ============================================================
-- GapSpark API — Deep Backfill Tracking (Migration 0013)
-- ============================================================
-- 目的: 新しく追加したアプリの過去レビュー（RSS の 2〜10 ページ目）を
--       一度だけ取りに行き、取り終えたことを記録する。
--
-- 【背景】
-- GitHub Actions は RSS の 1 ページ目（最新 50 件）しか取っていない。
-- 新しく追加したアプリはレビュー 50 件・ネガティブ 25 件前後で始まり、
-- 窓の回転が 1 回で終わってしまう。RSS は 10 ページ（500 件）まで取れるので、
-- 追加直後に一度だけ深掘りする。
--
-- 【「空のページ」を信じない理由】
-- Apple は IP によって、エラーではなく「正しい形の空のフィード」を返して断る
-- （2026-10-11、開発環境から実測。Actions が毎日取れているアプリでも空）。
-- 「レビューが無いアプリ」と見分けがつかないので、空のページを見ただけで
-- 「深掘り済み」にすると、ブロック中に全アプリを済みにして二度とやり直さない。
-- 1 ページ目にレビューがあった（＝フィードが生きている）ときだけ、
-- 後続ページの空を「本当の終わり」と信じる。決着しなければ試行回数を数え、
-- 3 回で諦める。
--
-- 既存の 101 アプリは、半年分のレビューがすでに溜まっているので「済み」にする。
-- この後に追加されるアプリだけが NULL で入り、深掘りの対象になる。
--
-- 適用（ワークフローより先に！）:
--   npx wrangler d1 execute gapspark-db --remote --file=./migrations/0013_deep_backfill.sql
-- ============================================================

-- 深掘りを終えた日時。NULL = まだ
ALTER TABLE tracked_apps ADD COLUMN deep_fetched_at TEXT;

-- 決着しなかった試行の回数（HTTP エラー、または 1 ページ目が空）。3 で諦める
ALTER TABLE tracked_apps ADD COLUMN deep_fetch_attempts INTEGER NOT NULL DEFAULT 0;

-- 既存アプリは対象外
UPDATE tracked_apps SET deep_fetched_at = datetime('now');
