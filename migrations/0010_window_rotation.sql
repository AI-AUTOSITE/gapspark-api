-- ============================================================
-- GapSpark API — Review Window Rotation (Migration 0010)
-- ============================================================
-- 目的: ペインポイント生成が「最もネガティブな50件」だけを何度も見る状態を
--       やめ、アプリごとにレビューの読み位置（オフセット）を進めていく。
--
-- 【背景】
-- レビュー取得は ORDER BY sentiment_score ASC LIMIT 50 で固定されていた。
-- この集合は時間が経ってもほぼ入れ替わらないため、同じアプリを何周しても
-- 新しい材料が入らず、重複除去で全部落ちていた。
--   実測（9/25）: 95アプリ中95アプリが empty_streak 2〜3（1〜2日待機）
--   生成ペース: 22.5件/日（初回掃引）→ 11.5件/日（2〜3周目）
-- Duolingo は 5,632件のネガレビューがあるのに、見ていたのは常に50件。
--
-- 【対策】
-- window_offset を持ち、1回ごとに 50 ずつ進める。末尾まで行ったら 0 に戻る。
--   1回目: 1〜50件目 / 2回目: 51〜100件目 / … / 末尾 → 0（1周）
-- バックオフの判定も「1回空振り」から「1周まるごと空振り」に変える。
-- 窓1つが空でも次の窓は当たりかもしれないので、1周するまでは6時間おきに進める。
--
-- 【empty_streak のリセットについて】
-- 既存の streak は「同じ50件を見て空振り」した回数であり、回転後の意味
-- （1周まるごと空振り）とは別物。引き継ぐと全アプリが1〜2日待機のまま
-- 回転が始まらないので、ここで 0 に戻す。これは意図した1回限りの操作。
--
-- 適用:
--   npx wrangler d1 execute gapspark-db --remote --file=./migrations/0010_window_rotation.sql
-- ============================================================

-- 次に読み始めるレビューの位置（0 = 最もネガティブな先頭から）
ALTER TABLE app_generation_state
    ADD COLUMN window_offset INTEGER NOT NULL DEFAULT 0;

-- 現在の周回で生まれたペインポイント数。末尾まで行ったとき、
-- これが 0 なら「1周まるごと空振り」として empty_streak を伸ばす
ALTER TABLE app_generation_state
    ADD COLUMN cycle_created INTEGER NOT NULL DEFAULT 0;

-- 旧ルールで積み上がった待機を解除し、全アプリを6時間サイクルに戻す
UPDATE app_generation_state SET empty_streak = 0;
